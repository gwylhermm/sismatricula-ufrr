private void atualizarTabela(
        javax.swing.JTable tabela,
        Object[][] dados) {

    javax.swing.table.DefaultTableModel modelo =
        (javax.swing.table.DefaultTableModel) tabela.getModel();

    modelo.setRowCount(0);

    for (Object[] linha : dados) {
        modelo.addRow(linha);
    }
}



